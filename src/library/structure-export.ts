import type { ActionItem, Chapter, TimedItem, TranscriptStructure } from './transcript-ai';

/**
 * Structured exports for extracted transcript content (roadmap TS-09).
 *
 * Chapters, decisions, action items and open questions are rendered to
 * Markdown, CSV, JSON and print-ready HTML.
 *
 * Unknown stays visibly unknown. An action item whose owner was never stated
 * renders as an explicit em dash in human-readable output and as an empty CSV
 * field, never as a guess and never as a blank that reads like an oversight.
 * An item with no resolvable timestamp is exported without one rather than
 * with a zero.
 *
 * PDF is produced by printing `structureHtml` from the browser rather than by
 * bundling a PDF engine: it keeps the dependency surface flat and the output
 * matches what the user sees.
 */

/** `H:MM:SS` for display, or `MM:SS` under an hour. */
export function formatTimestamp(seconds: number): string {
  const total = Math.max(0, Math.floor(seconds));
  const hh = Math.floor(total / 3600);
  const mm = Math.floor((total % 3600) / 60);
  const ss = total % 60;
  const pad = (value: number) => String(value).padStart(2, '0');
  return hh > 0 ? `${hh}:${pad(mm)}:${pad(ss)}` : `${mm}:${pad(ss)}`;
}

const stamp = (item: { startSeconds: number | null }): string =>
  item.startSeconds === null ? '' : `[${formatTimestamp(item.startSeconds)}] `;

/** Nothing extracted at all, so callers can offer an honest empty state. */
export const isStructureEmpty = (structure: TranscriptStructure): boolean =>
  structure.chapters.length === 0 && structure.decisions.length === 0
  && structure.actionItems.length === 0 && structure.openQuestions.length === 0;

const UNKNOWN = '—';

function section(heading: string, items: TimedItem[]): string[] {
  if (items.length === 0) return [];
  return [`## ${heading}`, '', ...items.map(item => `- ${stamp(item)}${item.text}`), ''];
}

function chapterSection(chapters: Chapter[]): string[] {
  if (chapters.length === 0) return [];
  return ['## Chapters', '', ...chapters.map(chapter => `- ${stamp(chapter)}${chapter.title}`), ''];
}

function actionSection(items: ActionItem[]): string[] {
  if (items.length === 0) return [];
  return [
    '## Action items', '',
    ...items.map(item => {
      const details = [
        `owner: ${item.owner ?? UNKNOWN}`,
        `due: ${item.due ?? UNKNOWN}`,
      ].join(', ');
      return `- [ ] ${stamp(item)}${item.text} (${details})`;
    }),
    '',
  ];
}

/** Full Markdown document for the extracted structure. */
export function structureMarkdown(structure: TranscriptStructure, title = 'Transcript analysis'): string {
  const lines = [`# ${title}`, ''];
  if (!structure.timestampsAvailable) {
    lines.push('> This transcript has no timings, so items below are not time-linked.', '');
  }
  lines.push(
    ...chapterSection(structure.chapters),
    ...section('Decisions', structure.decisions),
    ...actionSection(structure.actionItems),
    ...section('Open questions', structure.openQuestions),
  );
  if (isStructureEmpty(structure)) lines.push('No chapters, decisions, action items or open questions were found.', '');
  lines.push(`_Generated by ${structure.provider} ${structure.model}. Review before relying on it._`, '');
  return lines.join('\n');
}

/** Chapters alone, for a player or a description field. */
export function chaptersMarkdown(structure: TranscriptStructure): string {
  if (structure.chapters.length === 0) return '';
  return structure.chapters.map(chapter => `${stamp(chapter)}${chapter.title}`.trim()).join('\n') + '\n';
}

/** Escape one CSV field per RFC 4180. */
function csvField(value: string | null): string {
  const text = value ?? '';
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/**
 * Action items as CSV.
 *
 * An unstated owner or due date is an empty field, not "unknown": a spreadsheet
 * distinguishes empty from a literal string, and writing "unknown" would make
 * it look like the transcript said so.
 */
export function actionItemsCsv(structure: TranscriptStructure): string {
  const rows = [['timestamp', 'seconds', 'task', 'owner', 'due'].join(',')];
  for (const item of structure.actionItems) {
    rows.push([
      csvField(item.startSeconds === null ? '' : formatTimestamp(item.startSeconds)),
      csvField(item.startSeconds === null ? '' : String(item.startSeconds)),
      csvField(item.text),
      csvField(item.owner),
      csvField(item.due),
    ].join(','));
  }
  // A trailing newline keeps the file well-formed for spreadsheet importers.
  return rows.join('\r\n') + '\r\n';
}

const escapeHtml = (value: string): string =>
  value.replace(/[&<>"']/g, character =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character]!));

function htmlList(heading: string, items: TimedItem[]): string {
  if (items.length === 0) return '';
  const entries = items.map(item =>
    `<li>${item.startSeconds === null ? '' : `<span class="t">${escapeHtml(formatTimestamp(item.startSeconds))}</span>`}`
    + `${escapeHtml(item.text)}</li>`).join('');
  return `<section><h2>${escapeHtml(heading)}</h2><ul>${entries}</ul></section>`;
}

/**
 * Print-ready HTML. Printing this to PDF from the browser is the PDF export
 * path; no PDF engine is bundled.
 */
export function structureHtml(structure: TranscriptStructure, title = 'Transcript analysis'): string {
  const actions = structure.actionItems.length === 0 ? '' : `<section><h2>Action items</h2><table>
<thead><tr><th>Task</th><th>Owner</th><th>Due</th><th>At</th></tr></thead><tbody>${
    structure.actionItems.map(item => `<tr><td>${escapeHtml(item.text)}</td>`
      + `<td>${item.owner ? escapeHtml(item.owner) : `<span class="u">${UNKNOWN}</span>`}</td>`
      + `<td>${item.due ? escapeHtml(item.due) : `<span class="u">${UNKNOWN}</span>`}</td>`
      + `<td>${item.startSeconds === null ? '' : escapeHtml(formatTimestamp(item.startSeconds))}</td></tr>`).join('')
  }</tbody></table></section>`;

  const chapters = structure.chapters.length === 0 ? '' : htmlList('Chapters',
    structure.chapters.map(chapter => ({ text: chapter.title, startSeconds: chapter.startSeconds, segmentIndex: chapter.segmentIndex })));

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8" />
<title>${escapeHtml(title)}</title>
<style>
  :root { color-scheme: light; }
  body { margin: 0 auto; padding: 32px; max-width: 46em; font: 14px/1.6 system-ui, -apple-system, Segoe UI, sans-serif; color: #111; background: #fff; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  h2 { font-size: 15px; margin: 26px 0 8px; }
  ul { margin: 0; padding-left: 20px; }
  li { margin: 3px 0; }
  .t { display: inline-block; min-width: 4.5em; color: #555; font-variant-numeric: tabular-nums; }
  .u { color: #777; }
  .note { padding: 8px 12px; margin: 12px 0; border-left: 3px solid #bbb; color: #555; }
  table { width: 100%; border-collapse: collapse; }
  th, td { padding: 6px 8px; border-bottom: 1px solid #ddd; text-align: left; vertical-align: top; }
  th { font-size: 12px; text-transform: uppercase; letter-spacing: .04em; color: #555; }
  footer { margin-top: 28px; padding-top: 10px; border-top: 1px solid #ddd; color: #666; font-size: 12px; }
  @media print { body { padding: 0; } section { break-inside: avoid; } }
</style></head>
<body>
<h1>${escapeHtml(title)}</h1>
${structure.timestampsAvailable ? '' : '<p class="note">This transcript has no timings, so items are not time-linked.</p>'}
${chapters}
${htmlList('Decisions', structure.decisions)}
${actions}
${htmlList('Open questions', structure.openQuestions)}
${isStructureEmpty(structure) ? '<p>No chapters, decisions, action items or open questions were found.</p>' : ''}
<footer>Generated by ${escapeHtml(structure.provider)} ${escapeHtml(structure.model)}. Review before relying on it.</footer>
</body></html>
`;
}

export const STRUCTURE_FORMATS = ['markdown', 'chapters', 'csv', 'json', 'html'] as const;
export type StructureFormat = (typeof STRUCTURE_FORMATS)[number];
export const isStructureFormat = (value: string): value is StructureFormat =>
  (STRUCTURE_FORMATS as readonly string[]).includes(value);

export const STRUCTURE_MIME: Record<StructureFormat, string> = {
  markdown: 'text/markdown',
  chapters: 'text/plain',
  csv: 'text/csv',
  json: 'application/json',
  html: 'text/html',
};

export const STRUCTURE_EXTENSION: Record<StructureFormat, string> = {
  markdown: 'md', chapters: 'txt', csv: 'csv', json: 'json', html: 'html',
};

/** Render the extracted structure in the requested format. */
export function renderStructure(format: StructureFormat, structure: TranscriptStructure, title?: string): string {
  switch (format) {
    case 'markdown': return structureMarkdown(structure, title);
    case 'chapters': return chaptersMarkdown(structure);
    case 'csv': return actionItemsCsv(structure);
    case 'html': return structureHtml(structure, title);
    case 'json': return JSON.stringify(structure, null, 2);
  }
}
