import { describe, expect, test } from 'bun:test';
import {
  actionItemsCsv, chaptersMarkdown, formatTimestamp, isStructureEmpty, isStructureFormat,
  renderStructure, structureHtml, structureMarkdown,
} from './structure-export';
import type { TranscriptStructure } from './transcript-ai';

const base: TranscriptStructure = {
  chapters: [{ title: 'Budget', text: 'Budget', startSeconds: 0, segmentIndex: 0 }],
  decisions: [{ text: 'Postpone the launch to March.', startSeconds: 64, segmentIndex: 1 }],
  actionItems: [
    { text: 'Send the revised figures.', owner: 'Marie', due: 'next Friday', startSeconds: 3725, segmentIndex: 2 },
    { text: 'Book the venue.', owner: null, due: null, startSeconds: null, segmentIndex: null },
  ],
  openQuestions: [{ text: 'Who signs off?', startSeconds: 120, segmentIndex: 3 }],
  provider: 'mistral', model: 'test-model', usage: null, timestampsAvailable: true,
};

const empty: TranscriptStructure = {
  chapters: [], decisions: [], actionItems: [], openQuestions: [],
  provider: 'mistral', model: 'test-model', usage: null, timestampsAvailable: false,
};

describe('timestamp formatting', () => {
  test('omits the hour under an hour and includes it above', () => {
    expect(formatTimestamp(0)).toBe('0:00');
    expect(formatTimestamp(64)).toBe('1:04');
    expect(formatTimestamp(3725)).toBe('1:02:05');
  });

  test('never renders a negative time', () => {
    expect(formatTimestamp(-5)).toBe('0:00');
  });
});

describe('Markdown export', () => {
  test('includes every section that has content', () => {
    const md = structureMarkdown(base, 'Team sync');
    expect(md).toContain('# Team sync');
    expect(md).toContain('## Chapters');
    expect(md).toContain('## Decisions');
    expect(md).toContain('## Action items');
    expect(md).toContain('## Open questions');
  });

  test('time-links items that have a resolved timestamp', () => {
    expect(structureMarkdown(base)).toContain('- [0:00] Budget');
    expect(structureMarkdown(base)).toContain('- [1:04] Postpone the launch to March.');
  });

  test('omits the timestamp entirely for an unlinked item', () => {
    const md = structureMarkdown(base);
    // The unlinked action item must not acquire a 0:00.
    expect(md).toContain('- [ ] Book the venue.');
    expect(md).not.toContain('[0:00] Book the venue.');
  });

  test('marks an unstated owner and due date as explicitly unknown', () => {
    expect(structureMarkdown(base)).toContain('- [ ] Book the venue. (owner: —, due: —)');
  });

  test('keeps a stated due date verbatim', () => {
    expect(structureMarkdown(base)).toContain('owner: Marie, due: next Friday');
  });

  test('warns when the transcript had no timings at all', () => {
    const untimed = { ...base, timestampsAvailable: false };
    expect(structureMarkdown(untimed)).toContain('no timings');
    expect(structureMarkdown(base)).not.toContain('no timings');
  });

  test('says so plainly when nothing was extracted', () => {
    expect(structureMarkdown(empty)).toContain('No chapters, decisions, action items or open questions were found.');
  });

  test('always attributes the provider and model', () => {
    expect(structureMarkdown(base)).toContain('Generated by mistral test-model');
  });

  test('omits empty sections rather than printing empty headings', () => {
    const only = { ...empty, decisions: [{ text: 'One thing.', startSeconds: null, segmentIndex: null }] };
    const md = structureMarkdown(only);
    expect(md).toContain('## Decisions');
    expect(md).not.toContain('## Chapters');
    expect(md).not.toContain('## Action items');
  });
});

describe('chapters export', () => {
  test('renders one chapter per line with its time', () => {
    expect(chaptersMarkdown(base)).toBe('[0:00] Budget\n');
  });

  test('is empty when there are no chapters', () => {
    expect(chaptersMarkdown(empty)).toBe('');
  });
});

describe('CSV export', () => {
  test('writes a header and one row per action item', () => {
    const rows = actionItemsCsv(base).trim().split('\r\n');
    expect(rows[0]).toBe('timestamp,seconds,task,owner,due');
    expect(rows).toHaveLength(3);
  });

  test('leaves an unknown owner and due as empty fields, not "unknown"', () => {
    const rows = actionItemsCsv(base).trim().split('\r\n');
    expect(rows[2]).toBe(',,Book the venue.,,');
    expect(actionItemsCsv(base)).not.toMatch(/unknown/i);
  });

  test('escapes commas, quotes and newlines', () => {
    const tricky: TranscriptStructure = {
      ...empty,
      actionItems: [{ text: 'Call "Bob", then wait\nand retry', owner: 'A, B', due: null, startSeconds: null, segmentIndex: null }],
    };
    const csv = actionItemsCsv(tricky);
    expect(csv).toContain('"Call ""Bob"", then wait\nand retry"');
    expect(csv).toContain('"A, B"');
  });

  test('ends with a newline so importers see a complete last row', () => {
    expect(actionItemsCsv(base).endsWith('\r\n')).toBe(true);
  });

  test('emits only a header when there are no action items', () => {
    expect(actionItemsCsv(empty)).toBe('timestamp,seconds,task,owner,due\r\n');
  });
});

describe('HTML export', () => {
  test('is a complete printable document', () => {
    const html = structureHtml(base, 'Team sync');
    expect(html.startsWith('<!doctype html>')).toBe(true);
    expect(html).toContain('<title>Team sync</title>');
    expect(html).toContain('@media print');
  });

  test('escapes untrusted text so extracted content cannot inject markup', () => {
    const hostile: TranscriptStructure = {
      ...empty,
      decisions: [{ text: '<script>alert(1)</script>', startSeconds: null, segmentIndex: null }],
    };
    const html = structureHtml(hostile);
    expect(html).not.toContain('<script>alert(1)</script>');
    expect(html).toContain('&lt;script&gt;');
  });

  test('escapes a hostile title too', () => {
    expect(structureHtml(empty, '</title><script>x</script>')).not.toContain('<script>x</script>');
  });

  test('shows unknown owner and due as a visible dash', () => {
    const html = structureHtml(base);
    expect(html).toContain('<span class="u">—</span>');
  });

  test('notes missing timings', () => {
    expect(structureHtml({ ...base, timestampsAvailable: false })).toContain('no timings');
  });
});

describe('format selection', () => {
  test('recognizes only the supported formats', () => {
    expect(isStructureFormat('markdown')).toBe(true);
    expect(isStructureFormat('csv')).toBe(true);
    expect(isStructureFormat('pdf')).toBe(false);
  });

  test('renders each format', () => {
    expect(renderStructure('markdown', base)).toContain('## Chapters');
    expect(renderStructure('chapters', base)).toContain('Budget');
    expect(renderStructure('csv', base)).toContain('timestamp,seconds');
    expect(renderStructure('html', base)).toContain('<!doctype html>');
    expect(JSON.parse(renderStructure('json', base)).chapters).toHaveLength(1);
  });
});

describe('empty detection', () => {
  test('distinguishes an empty result from a populated one', () => {
    expect(isStructureEmpty(empty)).toBe(true);
    expect(isStructureEmpty(base)).toBe(false);
  });
});
